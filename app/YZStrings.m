NSString *YZT(NSString *russian) {
    NSDictionary *table = nil;
    switch ([YZSettings language]) {
    case YZLanguageRussian: return russian;
    case YZLanguageEnglish: table = YZEnglish(); break;
    case YZLanguageJapanese: table = YZJapanese(); break;
    }
    NSString *translated = [table objectForKey:russian];
    return translated ? translated : russian;
}
